/** Derive the offline login adapter from the installed home GhostFibers source.
 * The renderer, defaults and hero settings remain owned by apps/home.
 * Run from any directory: node test/build-login-background.mjs
 */
import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { createHash } from "node:crypto";
import vm from "node:vm";

const here = dirname(fileURLToPath(import.meta.url));
const home = resolve(here, "../../../apps/home");
const source = await readFile(resolve(home, "src/components/GhostFibers.jsx"), "utf8");
const hero = await readFile(resolve(home, "src/components/hero-background.tsx"), "utf8");
const license = await readFile(resolve(home, "licenses/react-bits.md"), "utf8");
function between(text, start, end) {
  const from = text.indexOf(start);
  const to = text.indexOf(end, from + start.length);
  if (from < 0 || to < 0)
    throw new Error("GhostFibers source changed; review adapter marker: " + start);
  return text.slice(from + start.length, to);
}
const helpers =
  "const MAX_RENDER_DIM" + between(source, "const MAX_RENDER_DIM", "const GhostFibers = (");
const defaults = between(source, "const GhostFibers = ({", "}) => {").replace("  ...rest", "");
const settings = between(source, "  const settings = ", "  const settingsRef = useRef(settings);");
const renderer = between(
  source,
  "  useEffect(() => {\n    const container = containerRef.current;",
  "  }, []);",
)
  .replace(
    "    const canvas = canvasRef.current;",
    "    const canvas = container.querySelector('canvas');",
  )
  .replace(
    "      [dots, dust, bright, down, up, composite].forEach(entry => gl.deleteProgram(entry.program));",
    "      [dots, dust, bright, down, up, composite].forEach(entry => gl.deleteProgram(entry.program));\n      gl.getExtension('WEBGL_lose_context')?.loseContext();",
  );
// Only literal appearance props are copied. Lifecycle props are owned by the login page.
const attributes = between(hero, "<GhostFibers", "/>");
const lifecycle = new Set(["mouseInteraction", "pulseOnClick", "intro", "paused"]);
const preset = {};
for (const match of attributes.matchAll(/(\w+)=(?:"([^"]*)"|\{([^}]+)\})/g)) {
  const [, name, literal, expression] = match;
  if (lifecycle.has(name)) continue;
  if (literal !== undefined) preset[name] = literal;
  else if (/^-?\d+(\.\d+)?$/.test(expression)) preset[name] = Number(expression);
  else throw new Error("Review nonliteral hero appearance setting: " + name);
}
if (!preset.glowColor || !preset.threads) throw new Error("Home hero settings were not found.");
const generated = `/* GENERATED by test/build-login-background.mjs. Do not edit.
 * Source: apps/home/src/components/GhostFibers.jsx
 * SHA-256: ${createHash("sha256").update(source).digest("hex")}
 * Home appearance: apps/home/src/components/hero-background.tsx
 * Renderer is shared with the home hero; the adapter only replaces React lifecycle.
 * ${license.replaceAll("\n", "\n * ")}
 */
(() => {
'use strict';
${helpers}
const normalize = ({${defaults}}) => (${settings.trim().replace(/;$/, "")});
const preset = ${JSON.stringify(preset)};
window.CompassLoginBackground = {
  mount(container, {paused = false, reduced = false} = {}) {
    const settingsRef = {current: normalize({...preset, paused: paused || reduced, mouseInteraction: !paused && !reduced, pulseOnClick: false, intro: !reduced})};
    const wakeRef = {current: null};
    const dispose = (() => {${renderer}\n})();
    if (!dispose) return null;
    return {
      setPaused(value) {
        settingsRef.current.paused = value || reduced;
        settingsRef.current.mouseInteraction = !value && !reduced;
        wakeRef.current?.();
      },
      dispose
    };
  }
};
})();
`;
new vm.Script(generated, { filename: "login-background.js" });
await writeFile(resolve(here, "../design/prototype/login-background.js"), generated);
console.log("Generated login background from home GhostFibers and hero appearance settings.");
