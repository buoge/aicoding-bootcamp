import { readFile, writeFile, mkdir } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import {
  databaseRoot,
  revision,
  revisions,
  loadRevision,
  sourceRecordSql,
  hash,
  cli,
  databaseMarker,
  literal,
  lockKey,
} from "./db-common.mjs";

export async function generateSql() {
  const sources = await Promise.all(revisions.map((id) => loadRevision(id)));
  const source = sources[0];
  const migrationSql = sources
    .map(
      (item) =>
        `${item.up}\n${sourceRecordSql(item)}\nINSERT INTO web_meta.pgmigrations(name,run_on) VALUES (${literal(item.id)},NOW());`,
    )
    .join("\n");
  const sql = `-- Generated by pnpm db:sql -F web; do not edit.\n-- Owner web/main; Feature 995; PostgreSQL 17; node-pg-migrate 9.0.0.\n-- empty -> ${revision}; transaction; recovery via verified backup/new database.\nBEGIN;\nSET LOCAL ROLE compass_web_owner;\nSELECT pg_advisory_xact_lock(${lockKey}::bigint);\nDO $$ BEGIN\n  IF NOT EXISTS (SELECT 1 FROM pg_database WHERE datname=current_database() AND shobj_description(oid,'pg_database')=${literal(databaseMarker)}) THEN RAISE EXCEPTION 'Unregistered database'; END IF;\n  IF EXISTS (SELECT 1 FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace WHERE n.nspname NOT IN ('pg_catalog','information_schema') AND n.nspname NOT LIKE 'pg_%') OR EXISTS (SELECT 1 FROM pg_namespace WHERE nspname NOT IN ('public','information_schema') AND nspname NOT LIKE 'pg_%') OR EXISTS (SELECT 1 FROM pg_proc p JOIN pg_namespace n ON n.oid=p.pronamespace WHERE n.nspname='public') THEN RAISE EXCEPTION 'Bootstrap requires an empty database'; END IF;\nEND $$;\nCREATE SCHEMA web_meta AUTHORIZATION compass_web_owner;\nCREATE TABLE web_meta.pgmigrations (id SERIAL PRIMARY KEY, name varchar(255) NOT NULL, run_on timestamp NOT NULL);\n${migrationSql}\nCOMMIT;\n`;
  const manifest = {
    owner: "web",
    databaseKey: "main",
    feature: "995",
    from: "empty",
    to: revision,
    engine: "PostgreSQL 17",
    tool: "node-pg-migrate 9.0.0",
    sourceRevision: "working-tree; fixed by source SHA-256",
    sources: sources.map((item) => ({ source: `migrations/${item.id}.sql`, sha256: item.sha256 })),

    bootstrap: "sql/bootstrap.sql",
    bootstrapSha256: hash(sql),
    incremental: `sql/upgrades/${revisions[0]}__${revision}.sql`,
    generate: "pnpm db:sql -F web",
    apply: `pnpm db:apply-sql -F web -- --from empty --to ${revision}`,
    prerequisites:
      "Provisioned owned empty web/main database, owner/migrator/runtime roles; managed target checks and lock",
    transaction: "single transaction",
    dataImpact:
      "Creates Web schema and stable tenant/workspace slugs; no users or new business rows",
    recovery:
      "Restore verified backup into a new owned database; verify permissions/revision; revoke sessions before switching",
  };
  const artifacts = new Map([
    ["bootstrap.sql", sql],
    ["manifest.json", JSON.stringify(manifest, null, 2) + "\n"],
  ]);
  const firstSql = sql.replace(
    migrationSql,
    `${source.up}\n${sourceRecordSql(source)}\nINSERT INTO web_meta.pgmigrations(name,run_on) VALUES (${literal(source.id)},NOW());`,
  );
  artifacts.set(
    `upgrades/empty__${source.id}.sql`,
    firstSql.replace(`empty -> ${revision}`, `empty -> ${source.id}`),
  );
  const next = sources[1];
  const upgrade = `-- Generated by pnpm db:sql -F web; do not edit.\n-- ${source.id} -> ${next.id}\nBEGIN;\nSET LOCAL ROLE compass_web_owner;\nSELECT pg_advisory_xact_lock(${lockKey}::bigint);\nDO $$ BEGIN\n IF NOT EXISTS (SELECT 1 FROM pg_database WHERE datname=current_database() AND shobj_description(oid,'pg_database')=${literal(databaseMarker)}) THEN RAISE EXCEPTION 'Unregistered database'; END IF;\n IF (SELECT count(*) FROM web_meta.pgmigrations) <> 1 OR NOT EXISTS (SELECT 1 FROM web_meta.pgmigrations WHERE name=${literal(source.id)}) OR (SELECT count(*) FROM web_meta.migration_source) <> 1 OR NOT EXISTS (SELECT 1 FROM web_meta.migration_source WHERE revision=${literal(source.id)} AND sha256=${literal(source.sha256)}) THEN RAISE EXCEPTION 'Unexpected starting revision or source checksum'; END IF;\nEND $$;\n${next.up}\n${sourceRecordSql(next)}\nINSERT INTO web_meta.pgmigrations(name,run_on) VALUES (${literal(next.id)},NOW());\nCOMMIT;\n`;
  artifacts.set(`upgrades/${source.id}__${next.id}.sql`, upgrade);
  return artifacts;
}

export async function writeSql(check = false) {
  const artifacts = await generateSql();
  if (!check) await mkdir(new URL("sql/upgrades/", databaseRoot), { recursive: true });
  for (const [name, content] of artifacts) {
    const target = new URL(`sql/${name}`, databaseRoot);
    if (check) {
      if ((await readFile(target, "utf8")) !== content) throw new Error(`SQL drift: ${name}`);
    } else await writeFile(target, content);
  }
}
